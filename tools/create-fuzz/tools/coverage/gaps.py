#!/usr/bin/env python3
"""Join measured missed branch groups to reviewed, source-pinned explanations."""
import argparse
import collections
import csv
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]


def revision(path):
    return subprocess.check_output(['git', '-C', str(path), 'rev-parse', 'HEAD'], text=True).strip()


def generate(input_path, definitions, reasons, subsystem, provenance, core_path=None):
    rules = definitions[subsystem]
    selected = []
    counts = collections.Counter()
    groups = collections.Counter()
    for row in csv.DictReader(input_path.read_text().splitlines(), delimiter='\t'):
        if not any(row['class'].startswith(p) for p in rules):
            continue
        candidates = [r for r in reasons if r['class'] == row['class']
                      and (r['method'] == '*' or r['method'] == row['method'] or r['method'] == row['method'].split('(')[0])
                      and int(r['first']) <= int(row['line']) <= int(r['last'])]
        if candidates:
            priority = lambda r: (-(int(r['last']) - int(r['first'])), r['method'] != '*')
            best = max(map(priority, candidates))
            candidates = [r for r in candidates if priority(r) == best]
            if len(candidates) > 1:
                raise ValueError(f'ambiguous reasons: {row}')
        category, why = ('UNCLASSIFIED', 'Source review and an explanation are still required.')
        if candidates:
            category, why = candidates[0]['category'], candidates[0]['why']
        count = int(row['missed branches'])
        if count <= 0:
            raise ValueError(f'invalid branch count: {row}')
        counts[category] += count
        groups[category] += 1
        selected.append((row, category, why))
    if core_path is not None:
        core_path.write_text(render_core(selected))
    return render_report(input_path, subsystem, provenance, selected, counts, groups), counts['UNCLASSIFIED']


def escape(value):
    return str(value).replace('|', '&#124;').replace('\n', ' ')


def render_report(input_path, subsystem, provenance, selected, counts, groups):
    lines = [f'# {subsystem}: never-reached branch groups', '',
             'Generated by `./run.sh fuzz gaps ' + subsystem + '`.', '',
             f'Fuzzer: `{provenance["fuzzer"]}`; engine: `{provenance["engine"]}`.',
             f'Create: `{provenance["create"]}`; reporter: `{provenance["reporter"]}`.',
             f'Campaign: `{provenance["command"]}`.',
             f'Input SHA-256: `{hashlib.sha256(input_path.read_bytes()).hexdigest()}`.',
             '', 'Counts refer to missed JaCoCo branch outcomes; groups are method/line pairs.',
             'A missed group can contain both covered and missed outcomes. Reasons do not identify individual edges.',
             '', '| Category | Groups | Missed branches |', '| --- | ---: | ---: |']
    counts.setdefault('UNCLASSIFIED', 0)
    for category in sorted(counts):
        lines.append(f'| {category} | {groups[category]} | {counts[category]} |')
    lines += ['', '## Harness work items', '']
    work = sorted({why for _, cat, why in selected if cat == 'harness-gap'})
    lines += ['- ' + why for why in work] or ['None classified.']
    lines += ['', '## Every missed group', '', '| Class | Method | Line | Missed | Category | Why |',
              '| --- | --- | ---: | ---: | --- | --- |']
    for row, category, why in selected:
        lines.append('| ' + ' | '.join(map(escape, [row['class'], row['method'], row['line'],
                                                   row['missed branches'], category, why])) + ' |')
    return '\n'.join(lines) + '\n'


def core_area(name):
    prefix = 'com/simibubi/create/content/kinetics/'
    if not name.startswith(prefix):
        return None
    relative = name.removeprefix(prefix)
    area = relative.split('/')[0]
    if area in {'RotationPropagator', 'TorquePropagator', 'KineticNetwork', 'chainDrive',
                'crank', 'gauge', 'gearbox', 'motor', 'simpleRelays', 'speedController',
                'steamEngine', 'transmission', 'waterwheel'}:
        return area
    if area == 'base' and not relative.startswith('base/BlockBreaking'):
        return area
    if area == 'belt' and (relative.count('/') == 1 or relative == 'belt/item/BeltConnectorItem'):
        return area
    return None


def render_core(selected):
    groups = collections.Counter()
    counts = collections.Counter()
    rows = []
    for row, category, why in selected:
        area = core_area(row['class'])
        if category != 'harness-gap' or area is None:
            continue
        groups[area] += 1
        counts[area] += int(row['missed branches'])
        rows.append([row['class'].removeprefix('com/simibubi/create/content/kinetics/'),
                     row['method'], row['line'], row['missed branches'], why])
    lines = ['# Remaining core kinetic harness gaps', '',
             'Generated by `./run.sh fuzz gaps kinetics` from the same campaign as the [kinetics report](kinetics.md).', '',
             'The core filter includes the kinetic network, base classes, transmissions, sources and root belt classes.',
             'Stationary block breaking, belt transport and contraption assemblies are outside this filter.', '',
             f'**{sum(counts.values())} missed core harness-gap branches in {len(rows)} groups remain.**', '',
             '| Core area | Groups | Missed branches |', '| --- | ---: | ---: |']
    lines.extend(f'| {area} | {groups[area]} | {counts[area]} |' for area in sorted(groups))
    lines += ['', '## Every remaining group', '', '| Class | Method | Create line | Missed | Remaining work |',
              '| --- | --- | ---: | ---: | --- |']
    lines.extend('| ' + ' | '.join(map(escape, row)) + ' |' for row in rows)
    return '\n'.join(lines) + '\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('subsystem', nargs='?')
    parser.add_argument('--input', type=Path, default=Path(os.environ.get('FUZZ_COVERAGE_REPORT',
                        str(Path(os.environ.get('FUZZ_DIR', ROOT / 'work')) / 'coverage'))) / 'never-reached.tsv')
    parser.add_argument('--output', type=Path, default=ROOT / 'docs/coverage')
    parser.add_argument('--provenance', type=Path)
    args = parser.parse_args()
    definitions = json.loads((ROOT / 'coverage/subsystems.json').read_text())
    reasons = list(csv.DictReader((ROOT / 'coverage/reasons.tsv').read_text().splitlines(), delimiter='\t'))
    allowed = {'client', 'unreachable', 'harness-gap', 'error-path'}
    for reason in reasons:
        if reason['category'] not in allowed and not reason['category'].startswith('out-of-scope:'):
            parser.error('invalid category: ' + reason['category'])
        if not reason['why'].strip():
            parser.error('empty explanation')
    provenance = json.loads((args.provenance or args.input.with_name("campaign.json")).read_text())
    review = json.loads((ROOT / "coverage/review.json").read_text())
    if provenance["create"] != review["create"]:
        parser.error("reason map was reviewed against a different Create commit")
    if not provenance.get("complete"):
        parser.error("coverage campaign did not complete")
    if provenance.get("never_reached_sha256") != hashlib.sha256(args.input.read_bytes()).hexdigest():
        parser.error("coverage input differs from completed campaign")
    provenance["reporter"] = revision(ROOT)
    subsystems = [args.subsystem] if args.subsystem else sorted(definitions)
    args.output.mkdir(parents=True, exist_ok=True)
    missing = 0
    classes = list(csv.DictReader(args.input.with_name('classes.tsv').read_text().splitlines(), delimiter='\t'))
    for subsystem in subsystems:
        if subsystem not in definitions:
            parser.error('unknown subsystem: ' + subsystem)
        absent = [p for p in definitions[subsystem] if not any(r['class'].startswith(p) for r in classes)]
        core_path = args.output / 'kinetics-core.md' if subsystem == 'kinetics' else None
        report, count = generate(args.input, definitions, reasons, subsystem, provenance, core_path)
        if absent:
            report += '\n## Missing denominator packages\n\n' + '\n'.join('- `' + p + '`' for p in absent) + '\n\nThese packages were absent from classes.tsv; this report cannot establish their coverage.\n'
            print(f"{subsystem}: missing denominator packages: {absent}", file=sys.stderr)
            missing += 1
        (args.output / (subsystem + '.md')).write_text(report)
        print(f'{subsystem}: {count} unexplained missed branches')
        missing += count
    return int(missing != 0)


if __name__ == '__main__':
    sys.exit(main())
